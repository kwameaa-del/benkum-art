"""Build the Works page (/works/): every published piece, curated as an exhibition.

Usage:
  python tools/render_works.py

Every folder under art/ with an index.html is a published piece. The page
reuses the About page's head, styles, header and footer, so it stays in step
with the rest of the site.

The arrangement below is Kae's approved curation (visual relationships only:
colour, density, portrait/landscape balance; never release order, country,
title or story). Desktop is built from three kinds of row:
  feature  one large piece beside a stack of two smaller ones
  row      pieces side by side at one shared height
On phones the same pieces recompose into one column: large landscapes at
88% and large portraits at 66% (centred), medium landscapes at 66% and small
ones at 54% on alternating sides, and small portraits in centred pairs. Widths are exact proportions of the container
(cqw), so every edge lines up at any width and nothing is cropped.

A new piece that is not yet placed in DESKTOP/PHONE is added at the end until
the layout is updated (the script warns).
"""
import html, pathlib, re
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
ABOUT = ROOT / "about" / "index.html"
OUT = ROOT / "works" / "index.html"
DESCRIPTION = "All the works of Benkum Art by Kwame Asiedu: art and stories from across Africa."

DESKTOP = [
    ("feature", "no-fixed-point", ["enough", "half-a-turn"], "left"),
    ("row", ["second-wind", "bound-to-outlast", "same-wish", "not-yet-on"]),
    ("feature", "already-landed", ["one-more", "between-the-marks"], "right"),
    ("row", ["steady-without-me", "the-shine-holds", "out-of-our-own"]),
    ("feature", "wired-time", ["where-i-remain", "still-turning"], "left"),
    ("row", ["what-stayed-open", "nothing-left-to-tie", "where-the-heat-was", "her-hands-go-first"]),
    ("feature", "wonder-dread", ["yet-to-let-go", "always-left-open"], "right"),
    ("row", ["a-second-behind", "before-it-works", "no-need-to-run", "still-red"]),
]
# (slug, width as a fraction of the column, side) or a pair of portraits.
PAIR_WIDTH = .84  # phones: a pair of small portraits spans 84% of the column, centred
PHONE = [
    ("no-fixed-point", .88, "c"), ("enough", .66, "r"), ("half-a-turn", .54, "l"),
    ["second-wind", "same-wish"], ("bound-to-outlast", .66, "r"), ("not-yet-on", .66, "c"), ("already-landed", .88, "c"),
    ("one-more", .54, "l"), ("between-the-marks", .66, "r"), ("steady-without-me", .88, "c"),
    ("the-shine-holds", .66, "c"), ("out-of-our-own", .66, "r"), ("where-i-remain", .66, "l"), ("wired-time", .88, "c"),
    ("still-turning", .66, "r"), ["what-stayed-open", "nothing-left-to-tie"], ["where-the-heat-was", "her-hands-go-first"],
    ("wonder-dread", .88, "c"), ("yet-to-let-go", .66, "l"), ("always-left-open", .66, "r"),
    ("a-second-behind", .88, "c"), ("still-red", .66, "l"), ["before-it-works", "no-need-to-run"],
]

CSS = """
  /* ---------- Works (curated exhibition; generated by tools/render_works.py) ---------- */
  .works-view { padding: 32px 0 40px; container-type: inline-size; }
  .works-grid { --g: 3.2cqw; display: flex; flex-direction: column; gap: var(--g); }
  .w-row, .w-feature { display: flex; gap: var(--g); align-items: flex-start; }
  .w-stack { display: flex; flex-direction: column; gap: var(--g); width: var(--sw); flex: none; }
  .w-item { display: block; flex: none; width: var(--dw); outline: none; }
  .w-item img { display: block; width: 100%; height: auto; background: #1c1b19; transition: opacity .2s; }
  .w-item:hover img { opacity: .86; }
  .w-item:focus-visible { outline: 2px solid var(--focus); outline-offset: 4px; }
  .w-br { display: none; }
  @container (max-width: 640px) {
    .works-grid { --g: 16px; flex-direction: row; flex-wrap: wrap; row-gap: 0; }
    .w-row, .w-feature, .w-stack { display: contents; }
    .w-item { width: var(--mw); order: var(--o); margin-bottom: var(--g); }
    /* Each row of the phone sequence starts on a fresh line. */
    .w-br { display: block; flex-basis: 100%; height: 0; order: var(--o); }
    .w-item.m-r { margin-left: auto; }
    .w-item.m-l { margin-right: auto; }
    .w-item.m-c { margin-left: auto; margin-right: auto; }
    .w-item.m-pl { margin-left: auto; }
    .w-item.m-pr { margin-right: auto; }
  }
  @media (max-width: 600px) { .works-view { margin-left: -32px; margin-right: -32px; } }
  @media (prefers-reduced-motion: reduce) { .w-item img { transition: none; } }
  .works-room { margin: 40px 0 0; text-align: center; font-size: 15px; font-style: italic; }
  .works-room a { color: var(--ink-soft); text-decoration: none; border-bottom: 1px solid var(--border); }
  .works-room a:hover { color: var(--accent); border-bottom-color: var(--accent); }
  .works-room a:focus-visible { outline: 2px solid var(--focus); outline-offset: 3px; }
"""


def pieces():
    out = {}
    for page in sorted((ROOT / "art").glob("*/index.html")):
        slug = page.parent.name
        text = page.read_text(encoding="utf-8")
        title = html.unescape(re.search(r"<title>([^<]*)</title>", text).group(1).split(" — ")[0]).strip()
        w, h = Image.open(ROOT / "assets" / "art" / f"{slug}.webp").size
        out[slug] = {"slug": slug, "title": title, "w": w, "h": h, "ar": w / h}
    return out


def n(v):
    return f"{v:.5f}".rstrip("0").rstrip(".")


def main():
    P = pieces()
    placed = [s for m in DESKTOP for s in ([m[1]] + m[2] if m[0] == "feature" else m[1])]
    phone = [s for e in PHONE for s in (e if isinstance(e, list) else [e[0]])]
    for name, seq in (("desktop", placed), ("phone", phone)):
        unknown = sorted(set(seq) - set(P))
        if unknown or len(seq) != len(set(seq)):
            raise SystemExit(f"{name} layout: unknown or repeated pieces {unknown}")
    # Each layout is checked on its own, so a piece placed in one list but not
    # the other still gets a spot in both.
    by_title = lambda s: P[s]["title"].lower()
    extra_d = sorted(set(P) - set(placed), key=by_title)
    extra_p = sorted(set(P) - set(phone), key=by_title)
    if extra_d:
        print("WARNING: not yet placed in the desktop layout, added at the end:", ", ".join(extra_d))
        DESKTOP.append(("row", extra_d))
    if extra_p:
        print("WARNING: not yet placed in the phone layout, added at the end:", ", ".join(extra_p))
        PHONE.extend((s, 1.0, "c") for s in extra_p)

    # Phone width, side and order for every piece.
    mob = {}
    for i, e in enumerate(PHONE):
        if isinstance(e, list):
            tot = sum(P[s]["ar"] for s in e)
            for s in e:
                side = "m-pl" if s == e[0] else "m-pr"
                mob[s] = (f"calc(({n(PAIR_WIDTH * 100)}cqw - var(--g)) * {n(P[s]['ar'] / tot)} - 0.5px)", side, 2 * i)
        else:
            s, frac, side = e
            mob[s] = (f"calc(100cqw * {n(frac)})", {"l": "m-l", "r": "m-r", "c": "m-c" if frac < 1 else ""}[side], 2 * i)

    first = set(placed[:4])

    def item(s, dw):
        p = P[s]; mw, cls, order = mob[s]
        lazy = "" if s in first else ' loading="lazy"'
        klass = f"w-item {cls}".strip()
        return (f'<a class="{klass}" href="/art/{s}/" style="--dw:{dw};--mw:{mw};--o:{order}">'
                f'<img src="/assets/art/{s}.webp" alt="{html.escape(p["title"])}" width="{p["w"]}" height="{p["h"]}"{lazy} decoding="async"></a>')

    parts = []
    for m in DESKTOP:
        if m[0] == "row":
            tot = sum(P[s]["ar"] for s in m[1]); k = len(m[1]) - 1
            parts.append('<div class="w-row">' + "".join(
                item(s, f"calc((100cqw - {k} * var(--g)) * {n(P[s]['ar'] / tot)})") for s in m[1]) + "</div>")
        else:
            _, big, stack, side = m
            a = P[big]["ar"]; inv = sum(1 / P[s]["ar"] for s in stack)
            # stack width c solves: a * (c * inv + g) + g + c = 100cqw
            sw = f"calc((100cqw - {n(1 + a)} * var(--g)) * {n(1 / (a * inv + 1))})"
            col = f'<div class="w-stack" style="--sw:{sw}">' + "".join(item(s, "100%") for s in stack) + "</div>"
            feat = item(big, "calc(100cqw - var(--g) - var(--sw))")
            parts.append(f'<div class="w-feature" style="--sw:{sw}">' + (feat + col if side == "left" else col + feat) + "</div>")
    breaks = "".join(f'<span class="w-br" style="--o:{2 * i - 1}" aria-hidden="true"></span>' for i in range(1, len(PHONE)))
    main_html = (
        '<main id="view-root"><div class="works-view">'
        '<h2 class="visually-hidden">Works</h2>'
        f'<div class="works-grid">{"".join(parts)}{breaks}</div>'
        '<p class="works-room"><a href="/cycle-i/in-your-space/" data-umami-event="room-open" data-umami-event-from="works">See the pieces in a room &rarr;</a></p>'
        '</div></main>'
    )

    t = ABOUT.read_text(encoding="utf-8")
    t = t.replace('<html lang="en">', '<html lang="en" data-cycle="i">', 1)
    t = re.sub(r"<title>[^<]*</title>", "<title>Works — Benkum Art</title>", t, count=1)
    t = re.sub(r'<meta name="description" content="[^"]*">', f'<meta name="description" content="{DESCRIPTION}">', t, count=1)
    t = t.replace("https://benkum.art/about/", "https://benkum.art/works/")
    t = re.sub(r'<meta property="og:title" content="[^"]*">', '<meta property="og:title" content="Works — Benkum Art">', t, count=1)
    t = re.sub(r'<meta property="og:description" content="[^"]*">', f'<meta property="og:description" content="{DESCRIPTION}">', t, count=1)
    t = t.replace('<meta property="og:type" content="profile">', '<meta property="og:type" content="website">')
    ld = (
        '<script type="application/ld+json">\n{\n  "@context": "https://schema.org",\n  "@type": "CollectionPage",\n'
        '  "url": "https://benkum.art/works/",\n  "name": "Works — Benkum Art",\n'
        f'  "description": "{DESCRIPTION}",\n'
        '  "author": { "@type": "Person", "name": "Kwame Asiedu", "url": "https://benkum.art/about/" }\n}\n</script>'
    )
    t = re.sub(r'<script type="application/ld\+json">.*?</script>', lambda m: ld, t, count=1, flags=re.S)
    t = t.replace("</style>", CSS + "</style>", 1)
    t = re.sub(r'<main id="view-root">.*?</main>', lambda m: main_html, t, count=1, flags=re.S)
    if 'class="visually-hidden"' in t and ".visually-hidden" not in t.split("</style>")[0]:
        t = t.replace("</style>", "  .visually-hidden { position: absolute; width: 1px; height: 1px; overflow: hidden; clip: rect(0 0 0 0); white-space: nowrap; }\n</style>", 1)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(t, encoding="utf-8", newline="\n")
    print(f"{len(P)} works -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
