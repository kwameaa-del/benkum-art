        ver = lambda rel: hashlib.sha1((OUT.parent / rel).read_bytes()).hexdigest()[:8]
        r["image"] = "/cycle-i/in-your-space/" + r["image"] + "?v=" + ver(r["image"])
        r["wall_mask"] = "/cycle-i/in-your-space/" + r["wall_mask"] + "?v=" + ver(r["wall_mask"])

