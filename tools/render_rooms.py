"""Build Cycle I's "In your space" room viewer (/cycle-i/in-your-space/).

Usage:
  python tools/render_rooms.py

Cycle I only. The viewer, its rooms and its data live under cycle-i/, so a later
cycle never inherits it; a future cycle gets its own folder and presentation.

Rooms and sizes come from tools/cycle-i-rooms.json. Pieces are every published
piece (art/*/index.html), in the Works page's curated order (never release order).
Each piece is drawn from its own site image at true scale: print size in cm x the
room's measured pixels per cm. The frame and mat are drawn in code; the artwork is
never altered. The page reuses the About page's head, header and footer.
"""
import html, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import render_works  # noqa: E402  (curated order and piece data)

ABOUT = ROOT / "about" / "index.html"
OUT = ROOT / "cycle-i" / "in-your-space" / "index.html"
DATA = ROOT / "tools" / "cycle-i-rooms.json"
TITLE = "In your space — Benkum Art"
DESCRIPTION = "See a Cycle I piece by Kwame Asiedu on a wall, at true scale, in a choice of rooms and sizes."

